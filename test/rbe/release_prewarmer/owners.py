"""Identify each configured producer of one object from the failed LLVM build."""

import collections
import hashlib
import json
import os
from pathlib import Path
import subprocess


root = Path(os.environ["RUNNER_TEMP"]) / "release-rbe"
records = {}
output = root / "public" / "owners.json"
client = [str(root / "bin/bazel"), "--nosystem_rc", "--nohome_rc"]
platform = "//test/rbe/release_prewarmer:amd64"
flags = [
    "--config=x86_64", "--config=race", "--extra_execution_platforms=" + platform, "--host_platform=" + platform,
    "--extra_toolchains=//test/rbe/go_bootstrap:linux_amd64_ash",
    "--@io_bazel_rules_go//go/config:experimental_use_sh_toolchain",
    "--extra_toolchains=//test/rbe/protoc_check:static_python", "--lockfile_mode=off",
    "--incompatible_use_native_posix_test_wrapper", "--test_arg=-test.v", "--test_env=GO_TEST_WRAP_TESTV=1",
    "--test_filter=^TestRun$", "--test_timeout=180", "--modify_execution_info=^TestRunner$=+no-remote-cache",
]


def inspect(name, options):
    query = 'outputs(".*/sched_setscheduler[.]pic[.]o$", deps(//runsc/boot:boot_test))'
    run = subprocess.run([*client, "aquery", *flags, *options, "--output=jsonproto", query],
                         stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True, timeout=480)
    row = records[name] = {"exit": run.returncode, "flags": options}
    if run.returncode:
        row["diagnostics"] = [line[:400] for line in run.stderr.splitlines() if line.startswith("ERROR:")][:10]
        return
    data = json.loads(run.stdout)
    configurations = {c["id"]: c for c in data["configuration"]}
    targets = {t["id"]: t["label"] for t in data["targets"]}
    artifacts = {a["id"]: a["pathFragmentId"] for a in data["artifacts"]}
    fragments = {f["id"]: f for f in data["pathFragments"]}

    def path(artifact):
        pieces = []
        fragment = artifacts[artifact]
        while fragment:
            entry = fragments[fragment]
            pieces.append(entry["label"])
            fragment = entry.get("parentId")
        return "/".join(reversed(pieces))

    producers = collections.defaultdict(list)
    for action in data["actions"]:
        obj = path(action["primaryOutputId"])
        if obj.endswith("/sched_setscheduler.pic.o"):
            producers[obj].append(action)
    row["occurrences"] = sum(map(len, producers.values()))
    row["paths"] = len(producers)
    row["collisions"] = []
    for obj, actions in sorted(producers.items()):
        if len(actions) < 2:
            continue
        group = {"output": obj, "producers": []}
        row["collisions"].append(group)
        for action in actions:
            cfg = configurations[action["configurationId"]]
            group["producers"].append(dict(owner=targets[action["targetId"]], configuration=cfg["checksum"],
                                           output_directory=cfg["mnemonic"], key=action["actionKey"],
                                           execution=action.get("executionPlatform"), compiler=action["arguments"][0]))
        first, second = actions[:2]
        group["only_in_first_argv"] = [x for x in first["arguments"] if x not in second["arguments"]][:20]
        group["only_in_second_argv"] = [x for x in second["arguments"] if x not in first["arguments"]][:20]
        if len(row["collisions"]) == 1:
            ids = [p["configuration"] for p in group["producers"][:2]]
            result = subprocess.run([*client, "config", *ids], capture_output=True, text=True, timeout=60)
            group["config_diff_exit"] = result.returncode
            group["config_diff"] = [line[:500] for line in result.stdout.splitlines() if line][:65]


for name, opts in [
    ("broad", ["--noincompatible_exclude_starlark_flags_from_exec_config"]),
    ("scoped", ["--incompatible_exclude_starlark_flags_from_exec_config"]),
]:
    inspect(name, opts)
    output.write_text(json.dumps(records, indent=2) + "\n")

# An aquery may visit fewer outputs than Bazel's conflict detector. In that
# case ask the original command for its own paired labels and configurations.
if not records["broad"].get("collisions"):
    original = [*client, "--bazelrc=" + str(root / "private.bazelrc"), "test", *flags,
                "--noincompatible_exclude_starlark_flags_from_exec_config", "--nocache_test_results",
                "--color=no", "--curses=no", "//runsc/boot:boot_test"]
    with (root / "original.log").open("w") as log:
        status = subprocess.run(["timeout", "--signal=INT", "--kill-after=15", "240", *original],
                                stdout=log, stderr=subprocess.STDOUT).returncode
    lines = (root / "original.log").read_text(errors="replace").splitlines()
    errors = []
    for i, line in enumerate(lines):
        if "generated by these conflicting actions" not in line:
            continue
        end = next((n for n in range(i + 1, min(i + 35, len(lines))) if lines[n].startswith(("ERROR:", "INFO:"))),
                   min(i + 35, len(lines)))
        errors.append([v[:1800] for v in lines[i:end]
                       if not any(x in v.lower() for x in ("api-key", "authorization", "token=", "remote_header", "bes_header"))])
        if len(errors) == 2:
            break
    records["original_test"] = {"exit": status, "first_conflicts": errors}
    output.write_text(json.dumps(records, indent=2) + "\n")


def analyze(name, flag):
    run = subprocess.run([*client, "test", *flags, flag, "--nobuild", "//runsc/boot:boot_test"],
                         capture_output=True, text=True, timeout=420)
    records[name] = {"exit": run.returncode, "action_conflict": "generated by these conflicting actions" in run.stderr,
                     "diagnostics": [s[:600] for s in run.stderr.splitlines() if s.startswith("ERROR:")][:4]}
    output.write_text(json.dumps(records, indent=2) + "\n")
    return records[name]


broad = "--noincompatible_exclude_starlark_flags_from_exec_config"
scoped = "--incompatible_exclude_starlark_flags_from_exec_config"
stock_broad = analyze("stock_broad_analysis", broad)
stock_scoped = analyze("stock_scoped_analysis", scoped)
module = Path("MODULE.bazel")
original = module.read_bytes()
anchor = b'        "//tools:rules_go_sdk_tool.patch",\n'
assert original.count(anchor) == 1
patch = Path("tools/qualification_rules_go_race_scope.patch")
patch.write_bytes((root / "harness/race_scope.patch").read_bytes())
module.write_bytes(original.replace(anchor, anchor + b'        "//tools:qualification_rules_go_race_scope.patch",\n'))
records["dependency_delta"] = {"label": "@io_bazel_rules_go//go/config:race", "set_scope": "target",
                                "patch_sha256": hashlib.sha256(patch.read_bytes()).hexdigest()}
explicit = analyze("explicit_race_scope_original_analysis", broad)
inspect("explicit_race_scope_original_owners", [broad])
if stock_broad["action_conflict"] and stock_scoped["exit"] == 0:
    # Verification on the byte-identical unpatched source takes precedence.
    module.write_bytes(original)
    patch.unlink()
    choice = scoped
elif explicit["exit"] == 0:
    choice = broad
else:
    choice = scoped
    analyze("explicit_race_scope_scoped_analysis", scoped)
(root / "boot-options").write_text(choice + "\n")
records["native_run"] = {"flag": choice, "explicit_race_scope": patch.exists()}
output.write_text(json.dumps(records, indent=2) + "\n")
