"""Exercise Skylib's hard-copy actions with and without Bazel's proposed API."""
import hashlib
import json
import os
from pathlib import Path
import stat
import subprocess
import sys
import time

stage = Path(os.environ["RUNNER_TEMP"]) / "skylib-copy-receipt"
stage.mkdir(exist_ok=True)
workspace = Path(os.environ["GITHUB_WORKSPACE"])
src = workspace / "skylib"
producer = workspace / "rules_python"
root = workspace / "consumer"
patch = root / "test/rbe/supplier-namespace/skylib-copy.patch"
lane = sys.argv[1]
bazel = sys.argv[2]
receipt = {"lane": lane, "started": time.time(), "commands": []}

def run(*args, expected=0, cwd=None):
    started = time.time()
    process = subprocess.run(args, cwd=cwd or root, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    with (stage / (lane+".log")).open("ab") as log:
        log.write(("$ "+" ".join(map(str,args))+"\n").encode())
        log.write(process.stdout)
        log.write(process.stderr)
    receipt["commands"].append({"command": list(map(str,args)), "exit": process.returncode,
                                "started": started, "ended": time.time()})
    if process.returncode != expected:
        print(process.stderr[-3900:].decode(errors="replace"), flush=True)
        raise ValueError(f"{args[:3]} exited {process.returncode}, expected {expected}")
    return process.stdout

def witness():
    fixture = Path(os.environ["RUNNER_TEMP"]) / ("skylib-fixture-"+lane)
    fixture.mkdir()
    # Use real supplier repositories while keeping their development-only graph
    # out of the consumer's module graph.
    (fixture / "MODULE.bazel").write_text(f'''
module(name = "copy_witness")
bazel_dep(name = "rules_python", version = "2.4.5")
bazel_dep(name = "bazel_skylib", version = "1.9.2")
local_path_override(module_name = "rules_python", path = "{producer}")
local_path_override(module_name = "bazel_skylib", path = "{src}")
''')
    (fixture / "fixture.bzl").write_text('''
def _generated_impl(ctx):
    out = ctx.actions.declare_file(ctx.label.name+".dat")
    ctx.actions.write(output = out, content = "generated bytes")
    return [DefaultInfo(files = depset([out]))]

generated = rule(implementation = _generated_impl)

def _link_impl(ctx):
    link = ctx.actions.declare_symlink(ctx.label.name+".link")
    ctx.actions.symlink(output = link, target_path = "generated.dat")
    return [DefaultInfo(files = depset([link]))]

link = rule(implementation = _link_impl)
''')
    (fixture / "BUILD.bazel").write_text('''
load("@bazel_skylib//rules:copy_file.bzl", "copy_file")
load("@rules_python//python/private/pypi:namespace_pkgs.bzl", "create_inits")
load(":fixture.bzl", "generated", "link")
create_inits(srcs = ["alpha/beta/example.py"])
generated(name = "generated")
link(name = "link")
copy_file(name = "binary", src = "all-bytes.bin", out = "copied.bin")
copy_file(name = "generated_copy", src = ":generated", out = "copied-generated.bin")
copy_file(name = "executable", src = "say.sh", out = "say-copy", is_executable = True)
copy_file(name = "link_by_request", src = "all-bytes.bin", out = "permitted-link", allow_symlink = True)
copy_file(name = "declared_link_input", src = ":link", out = "declared-link-copy")
''')
    payload = bytes(range(256))*16384
    (fixture/"all-bytes.bin").write_bytes(payload)
    (fixture/"say.sh").write_text("#!/bin/sh\nprintf 'skylib-executable\\n'\n")
    def bz(*args, **kw):
        return run(bazel, *args, cwd=fixture, **kw)
    receipt["version"] = bz("version").decode()
    def actions(label):
        graph = json.loads(bz("aquery","--output=jsonproto", label))
        copy_mnemonics = {"Copy","CopyFile","Symlink","ExecutableSymlink"}
        return [a["mnemonic"] for a in graph["actions"] if a["mnemonic"] in copy_mnemonics]
    targets = ["//:_cp_0_namespace","//:_cp_1_namespace","//:binary","//:generated_copy"]
    mnemonics = {t:actions(t) for t in [*targets, "//:executable","//:declared_link_input","//:link_by_request"]}
    receipt["actions"] = mnemonics
    assert mnemonics["//:executable"] == ["CopyFile"]
    assert mnemonics["//:declared_link_input"] == ["CopyFile"]
    assert mnemonics["//:link_by_request"] == ["Symlink"]
    native = lane == "native"
    expected_mnemonic = "Copy" if native else "CopyFile"
    for t in targets:
        assert mnemonics[t] == [expected_mnemonic], (t, mnemonics[t])
    if not native:
        bz("build", "--action_env=PATH=/no-executables", "//:_cp_0_namespace", expected=1)
        assert b"cp: command not found" in (stage / (lane+".log")).read_bytes()
    opts = ["--action_env=PATH=/no-executables"] if native else []
    bz("build", *opts, *targets)
    output = Path(bz("info","bazel-bin").decode().strip())
    template = (producer/"python/private/pypi/namespace_pkg_tmpl.py").read_bytes()
    receipt["outputs"] = {}
    for name,data in [("alpha/__init__.py",template),("alpha/beta/__init__.py",template),("copied.bin",payload),("copied-generated.bin",b"generated bytes")]:
        dest = output / name
        mode = dest.lstat().st_mode
        assert stat.S_ISREG(mode) and dest.read_bytes() == data, name
        receipt["outputs"][name] = {"sha256": hashlib.sha256(data).hexdigest(),"size":len(data),"mode":stat.filemode(mode)}
    assert b"skylib-executable\n" in bz("run","//:executable")
    return "PASS"

try:
    receipt["skylib"] = run("git","rev-parse","HEAD",cwd=src).decode().strip()
    receipt["rules_python"] = run("git","rev-parse","HEAD",cwd=producer).decode().strip()
    receipt["patch_sha256"] = hashlib.sha256(patch.read_bytes()).hexdigest()
    receipt["status"] = witness()
except Exception as error:
    receipt["status"] = "FAIL"
    receipt["error"] = repr(error)
    raise
finally:
    receipt["ended"] = time.time()
    (stage/(lane+".json")).write_text(json.dumps(receipt,indent=2)+"\n")
