type compatRelease struct {
	cli, sidecars string
}

// Each command gets a fresh process and exactly one matching CLI/sidecar pair.
// Real files also prevent a detached guest holding a command's output pipe open.
func (r compatRelease) command(t *testing.T, conf *config.Config, wantError string, args ...string) []byte {
	t.Helper()
	cmd := exec.Command(r.cli, append(conf.ToFlags(), args...)...)
	for _, entry := range os.Environ() {
		if !strings.HasPrefix(entry, "GVISOR_SIDECAR_BINARIES_DIR=") {
			cmd.Env = append(cmd.Env, entry)
		}
	}
	cmd.Env = append(cmd.Env, "GVISOR_SIDECAR_BINARIES_DIR="+r.sidecars)
	out, err := os.CreateTemp(t.TempDir(), "stdout")
	if err != nil {
		t.Fatal(err)
	}
	defer out.Close()
	diag, err := os.CreateTemp(t.TempDir(), "stderr")
	if err != nil {
		t.Fatal(err)
	}
	defer diag.Close()
	cmd.Stdout, cmd.Stderr = out, diag
	exit := testutil.RunCmd(cmd)
	stderr, err := os.ReadFile(diag.Name())
	if err != nil {
		t.Fatal(err)
	}
	if wantError != "" {
		if exit == nil || !bytes.Contains(stderr, []byte(wantError)) {
			t.Fatalf("%s: wanted %q; got %v, %s", args[0], wantError, exit, stderr)
		}
		return nil
	}
	if exit != nil {
		t.Fatalf("%s: %v: %s", args[0], exit, stderr)
	}
	data, err := os.ReadFile(out.Name())
	if err != nil {
		t.Fatal(err)
	}
	return data
}

func compatDigest(t *testing.T, path string) [32]byte {
	t.Helper()
	f, err := os.Open(path)
	if err != nil {
		t.Fatal(err)
	}
	defer f.Close()
	h := sha256.New()
	if _, err := io.Copy(h, f); err != nil {
		t.Fatal(err)
	}
	return [32]byte(h.Sum(nil))
}

func compatEnvelope(t *testing.T, path string) (statefile.Reader, map[string]string) {
	t.Helper()
	f, err := os.Open(path)
	if err != nil {
		t.Fatal(err)
	}
	r, md, err := statefile.NewReader(f, nil)
	if err != nil {
		f.Close()
		t.Fatal(err)
	}
	return r, md
}

// Preserve the complete genuine decompressed payload, varying only the named
// metadata field and the timestamp generated by the standard envelope writer.
func compatRewrap(t *testing.T, src, format, version string) string {
	t.Helper()
	r, md := compatEnvelope(t, src)
	defer r.Close()
	delete(md, statefile.PayloadFormatKey)
	delete(md, "_timestamp")
	md["runsc_version"] = version
	dir := t.TempDir()
	f, err := os.Create(filepath.Join(dir, checkpointfiles.StateFileName))
	if err != nil {
		t.Fatal(err)
	}
	defer f.Close()
	w, err := statefile.NewWriterWithFormat(f, nil, md, format)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := io.Copy(w, r); err != nil {
		t.Fatal(err)
	}
	if err := r.Verify(); err != nil {
		t.Fatal(err)
	}
	if err := w.Close(); err != nil {
		t.Fatal(err)
	}
	return dir
}

func TestCheckpointFormatCompatibility(t *testing.T) {
	const stamp = "qualification-memoryfile-compat"
	stop := testutil.StartReaper()
	defer stop()
	oldDir := os.Getenv("GVISOR_CKPT_OLD_RELEASE")
	if oldDir == "" {
		t.Fatal("old release missing")
	}
	old := compatRelease{filepath.Join(oldDir, "runsc"), filepath.Join(oldDir, "gvisor-bin")}
	current := compatRelease{specutils.ExePath, os.Getenv("GVISOR_SIDECAR_BINARIES_DIR")}
	tree := []string{"--target-dir=/witness", "--depth=1", "--file-per-level=2", "--file-size=8192", "--seed=31"}
	for _, tc := range []struct {
		name           string
		writer, reader compatRelease
		compression    string
		fsOnly         bool
	}{
		{"old-inline-to-new", old, current, "flate-best-speed", false},
		{"new-inline-to-new", current, current, "flate-best-speed", false},
		{"new-split-to-old", current, old, "none", false},
		{"new-filesystem-to-old", current, old, "", true},
	} {
		t.Run(tc.name, func(t *testing.T) {
			conf := testutil.TestConfig(t)
			conf.Network = config.NetworkNone
			conf.StateEngine = config.StateEngineWire
			if err := conf.Overlay2.Set("root:self"); err != nil {
				t.Fatal(err)
			}
			spec := idleGuestSpec(t)
			spec.Root.Readonly = false
			spec.Annotations = map[string]string{specutils.ContainerdContainerNameAnnotation: "checkpoint-root"}
			_, bundle, cleanup, err := testutil.SetupContainer(spec, conf)
			if err != nil {
				t.Fatal(err)
			}
			defer cleanup()
			// Full restores keep the same host lower files. For an independently
			// mounted filesystem restore, provide a clean equivalent root.
			bundle2 := bundle
			if tc.fsOnly {
				spec2 := idleGuestSpec(t)
				spec2.Root.Readonly = false
				spec2.Annotations = spec.Annotations
				second, clean2, err := testutil.SetupBundleDir(spec2)
				if err != nil {
					t.Fatal(err)
				}
				defer clean2()
				bundle2 = second
			}
			for _, release := range []compatRelease{old, current} {
				out := release.command(t, conf, "", "--version")
				if strings.SplitN(string(out), "\n", 2)[0] != "runsc version "+stamp {
					t.Fatalf("unexpected recipe stamp: %q", out)
				}
			}
			srcID, dstID := testutil.RandomContainerID(), testutil.RandomContainerID()
			tc.writer.command(t, conf, "", "create", "--bundle="+bundle, srcID)
			tc.writer.command(t, conf, "", "start", srcID)
			tc.writer.command(t, conf, "", append([]string{"exec", srcID, "/test_app", "fsTreeCreate"}, tree...)...)
			dir := t.TempDir()
			if tc.fsOnly {
				tc.writer.command(t, conf, "", "fscheckpoint", "--image-path="+dir, srcID)
			} else {
				tc.writer.command(t, conf, "", "checkpoint", "--compression="+tc.compression, "--image-path="+dir, srcID)
			}
			tc.writer.command(t, conf, "", "delete", "--force", srcID)
			if tc.fsOnly {
				tc.reader.command(t, conf, "", "create", "--bundle="+bundle2, "--fs-restore-image-path="+dir, dstID)
				tc.reader.command(t, conf, "", "start", dstID)
			} else {
				image := filepath.Join(dir, checkpointfiles.StateFileName)
				digest := compatDigest(t, image)
				r, md := compatEnvelope(t, image)
				if err := r.Close(); err != nil {
					t.Fatal(err)
				}
				wantFormat := ""
				if tc.name == "new-inline-to-new" {
					wantFormat = "framed-memoryfile-v1"
				}
				if md[statefile.PayloadFormatKey] != wantFormat || md["runsc_version"] != stamp {
					t.Fatalf("unexpected checkpoint format or version")
				}
				if wantFormat != "" {
					var prior [32]byte
					for i, release := range []compatRelease{old, current} {
						out := release.command(t, conf, "", "statefile", image)
						if !bytes.Contains(out, []byte(".Kernel]{")) || !bytes.Contains(out, []byte("privateMemoryFileMetadata")) {
							t.Fatalf("generic dump missed kernel or trailing private-owner graph")
						}
						sum := sha256.Sum256(out)
						if i != 0 && sum != prior {
							t.Fatal("generic dump outputs differ")
						}
						prior = sum
					}
					t.Logf("COMPAT_DUMP image=%x text=%x", digest, prior)
					for _, negative := range []struct {
						name, format, version, diagnostic string
						release                           compatRelease
					}{
						{"unknown-format", "qualification-unknown", stamp, "unsupported checkpoint payload format", current},
						{"different-release", wantFormat, "qualification-other-release", "runsc version does not match across checkpoint restore", old},
					} {
						t.Run(negative.name, func(t *testing.T) {
							rewritten := compatRewrap(t, image, negative.format, negative.version)
							negative.release.command(t, conf, negative.diagnostic, "restore", "--detach", "--background=false", "--direct-io=off", "--bundle="+bundle2, "--image-path="+rewritten, testutil.RandomContainerID())
						})
					}
				}
				tc.reader.command(t, conf, "", "restore", "--detach", "--background=false", "--direct-io=off", "--bundle="+bundle2, "--image-path="+dir, dstID)
				if compatDigest(t, image) != digest {
					t.Fatal("checkpoint changed across restore")
				}
				t.Logf("COMPAT_RESTORED image=%x format=%q", digest, wantFormat)
			}
			defer tc.reader.command(t, conf, "", "delete", "--force", dstID)
			ps := tc.reader.command(t, conf, "", "ps", "--format=json", dstID)
			if strings.TrimSpace(string(ps)) != "[1]" {
				t.Fatalf("restored PIDs: %q", ps)
			}
			tab := strings.Split(strings.TrimSpace(string(tc.reader.command(t, conf, "", "ps", dstID))), "\n")
			if len(tab) != 2 {
				t.Fatalf("expected one guest process")
			}
			cols := strings.Fields(tab[1])
			if len(cols) != 9 || cols[1] != "1" || cols[8] != "test_app" {
				t.Fatalf("restored process: %q", cols)
			}
			tc.reader.command(t, conf, "", append([]string{"exec", dstID, "/test_app", "fsTreeVerify"}, tree...)...)
			t.Log("COMPAT_GUEST pid=1 files=2 bytes_each=8192")
		})
	}
}

// Exercise the same ordinary split checkpoint against each implementation of
// the marker check. A fork-only observation at the original Restore RPC error
// defer snapshots whether NewAsyncMFLoader returned an installed loader.
func TestSplitFormatRejectionBeforePages(t *testing.T) {
	const stamp = "qualification-memoryfile-compat-dirty"
	stop := testutil.StartReaper()
	defer stop()
	lateDir := os.Getenv("GVISOR_CKPT_LATE_RELEASE")
	if lateDir == "" {
		t.Fatal("late-validator release missing")
	}
	late := compatRelease{filepath.Join(lateDir, "runsc"), filepath.Join(lateDir, "gvisor-bin")}
	current := compatRelease{specutils.ExePath, os.Getenv("GVISOR_SIDECAR_BINARIES_DIR")}

	conf := testutil.TestConfig(t)
	conf.Network = config.NetworkNone
	conf.StateEngine = config.StateEngineWire
	spec := idleGuestSpec(t)
	_, bundle, cleanup, err := testutil.SetupContainer(spec, conf)
	if err != nil {
		t.Fatal(err)
	}
	defer cleanup()
	for _, runtime := range []compatRelease{late, current} {
		out := runtime.command(t, conf, "", "--version")
		if strings.SplitN(string(out), "\n", 2)[0] != "runsc version "+stamp {
			t.Fatalf("unexpected observation build stamp: %q", out)
		}
	}
	source := testutil.RandomContainerID()
	current.command(t, conf, "", "create", "--bundle="+bundle, source)
	current.command(t, conf, "", "start", source)
	original := t.TempDir()
	current.command(t, conf, "", "checkpoint", "--compression=none", "--image-path="+original, source)
	current.command(t, conf, "", "delete", "--force", source)
	image := filepath.Join(original, checkpointfiles.StateFileName)
	r, md := compatEnvelope(t, image)
	if err := r.Close(); err != nil {
		t.Fatal(err)
	}
	if _, present := md[statefile.PayloadFormatKey]; present || md["runsc_version"] != stamp {
		t.Fatal("unexpected real split envelope")
	}
	t.Run("valid-split", func(t *testing.T) {
		id := testutil.RandomContainerID()
		current.command(t, conf, "", "restore", "--detach", "--direct-io=off", "--background=false", "--bundle="+bundle, "--image-path="+original, id)
		defer current.command(t, conf, "", "delete", "--force", id)
		if got := current.command(t, conf, "", "ps", "--format=json", id); strings.TrimSpace(string(got)) != "[1]" {
			t.Fatalf("restored PIDs: %q", got)
		}
	})
	// Link the exact originals into the rewrapped directory. Opening the
	// files is permitted in both arms. Only starting the decoder is at issue.
	rejected := compatRewrap(t, image, "framed-memoryfile-v1", stamp)
	pageNames := []string{checkpointfiles.PagesMetadataFileName, checkpointfiles.PagesFileName}
	var sums [2][32]byte
	for i, name := range pageNames {
		src := filepath.Join(original, name)
		dst := filepath.Join(rejected, name)
		if err := os.Link(src, dst); err != nil {
			t.Fatal(err)
		}
		sums[i] = compatDigest(t, src)
	}
	rejectedHash := compatDigest(t, filepath.Join(rejected, checkpointfiles.StateFileName))
	for _, tc := range []struct {
		name      string
		runtime   compatRelease
		installed string
	}{{"previous", late, "true"}, {"corrected", current, "false"}} {
		t.Run(tc.name, func(t *testing.T) {
			want := "qualification split loader installed=" + tc.installed + ": unsupported checkpoint payload format"
			tc.runtime.command(t, conf, want, "restore", "--detach", "--direct-io=off", "--background=false", "--bundle="+bundle, "--image-path="+rejected, testutil.RandomContainerID())
			for i, name := range pageNames {
				if compatDigest(t, filepath.Join(rejected, name)) != sums[i] {
					t.Fatal("original pages changed")
				}
			}
			if compatDigest(t, filepath.Join(rejected, checkpointfiles.StateFileName)) != rejectedHash {
				t.Fatal("rewrapped statefile changed")
			}
			t.Logf("SPLIT_ORDER arm=%s installed=%s checkpoint=%x metadata=%x pages=%x", tc.name, tc.installed, rejectedHash, sums[0], sums[1])
		})
	}
}
