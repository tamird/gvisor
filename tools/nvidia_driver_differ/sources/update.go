// Binary update pins public source archives for nvproxy's supported drivers.
package main

import (
	"context"
	"crypto/sha256"
	"encoding/hex"
	"flag"
	"fmt"
	"io"
	"net/http"
	"os"
	"path/filepath"
	"slices"
	"strings"
	"time"

	"github.com/google/go-github/v84/github"
	"gvisor.dev/gvisor/pkg/sentry/devices/nvproxy"
	"gvisor.dev/gvisor/pkg/sentry/devices/nvproxy/nvconf"
)

const driverRepo = "https://github.com/NVIDIA/open-gpu-kernel-modules"

// sourcePin records an immutable source archive. An empty commit means the
// complete tag list contains no matching version.
type sourcePin struct {
	version string
	commit  string
	sha256  string
}

func archiveURL(commit string) string {
	return driverRepo + "/archive/" + commit + ".tar.gz"
}

func fetch(ctx context.Context, client *http.Client, url string) (*http.Response, error) {
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, url, nil)
	if err != nil {
		return nil, err
	}
	req.Header.Set("User-Agent", "gvisor-nvidia-source-updater")
	return client.Do(req)
}

// publicTags returns the source commits for NVIDIA's published driver versions.
func publicTags(ctx context.Context, client *github.Client) (map[string]string, error) {
	commits := make(map[string]string)
	opts := &github.ListOptions{PerPage: 100}
	for {
		tags, resp, err := client.Repositories.ListTags(ctx, "NVIDIA", "open-gpu-kernel-modules", opts)
		if err != nil {
			return nil, err
		}
		for _, tag := range tags {
			name, commit := tag.GetName(), tag.GetCommit().GetSHA()
			if name == "" || commit == "" {
				return nil, fmt.Errorf("incomplete NVIDIA source tag: name %q, commit %q", name, commit)
			}
			commits[name] = commit
		}
		if resp.NextPage == 0 {
			return commits, nil
		}
		opts.Page = resp.NextPage
	}
}

func pinSource(ctx context.Context, client *http.Client, version, commit string) (sourcePin, error) {
	pin := sourcePin{version: version, commit: commit}
	if commit == "" {
		return pin, nil
	}
	archive, err := fetch(ctx, client, archiveURL(pin.commit))
	if err != nil {
		return pin, fmt.Errorf("download %s: %w", version, err)
	}
	defer archive.Body.Close()
	if archive.StatusCode != http.StatusOK {
		return pin, fmt.Errorf("download %s: HTTP %s", version, archive.Status)
	}
	hash := sha256.New()
	if _, err := io.Copy(hash, archive.Body); err != nil {
		return pin, fmt.Errorf("hash %s: %w", version, err)
	}
	pin.sha256 = hex.EncodeToString(hash.Sum(nil))
	return pin, nil
}

func render(pins []sourcePin) string {
	var sources strings.Builder
	fmt.Fprintln(&sources, "# Generated by //tools/nvidia_driver_differ/sources:update. Do not edit.")
	fmt.Fprintln(&sources, "\"\"\"Public NVIDIA source commits and SHA-256 hashes. None denotes a missing tag.\"\"\"")
	fmt.Fprintln(&sources, "\nDRIVER_PINS = {")
	for _, pin := range pins {
		if pin.commit == "" {
			fmt.Fprintf(&sources, "    %q: None,\n", pin.version)
		} else {
			fmt.Fprintf(&sources, "    %q: (%q, %q),\n", pin.version, pin.commit, pin.sha256)
		}
	}
	fmt.Fprintln(&sources, "}")
	return sources.String()
}

func update(ctx context.Context, workspace string, candidates []string) error {
	nvproxy.Init()
	versions := nvproxy.SupportedDrivers()
	for _, s := range candidates {
		version, err := nvconf.DriverVersionFrom(s)
		if err != nil {
			return err
		}
		if !slices.Contains(versions, version) {
			versions = append(versions, version)
		}
	}
	client := &http.Client{Timeout: 5 * time.Minute}
	commits, err := publicTags(ctx, github.NewClient(client))
	if err != nil {
		return fmt.Errorf("list NVIDIA source tags: %w", err)
	}
	var pins []sourcePin
	for _, version := range versions {
		pin, err := pinSource(ctx, client, version.String(), commits[version.String()])
		if err != nil {
			return err
		}
		pins = append(pins, pin)
		if pin.commit == "" {
			fmt.Fprintf(os.Stderr, "%s: no public source version\n", version)
		} else {
			fmt.Fprintf(os.Stderr, "%s: %s\n", version, pin.commit)
		}
	}
	path := filepath.Join(workspace, "tools/nvidia_driver_differ/driver_pins.bzl")
	return os.WriteFile(path, []byte(render(pins)), 0644)
}

func main() {
	workspace := flag.String("workspace", os.Getenv("BUILD_WORKSPACE_DIRECTORY"), "repository root to update")
	flag.Parse()
	if *workspace == "" {
		flag.Usage()
		os.Exit(1)
	}
	if err := update(context.Background(), *workspace, flag.Args()); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
